/** The `gaussHermiteQuadratuteTest` test the gaussHermiteQuadratuteTest class.
 *  > runMain scalation.random.gaussHermiteQuadratuteTest
 */
@main def gaussHermiteQuadratuteTest (): Unit =

    banner ("--- Verification Matrix for Gauss-Hermite Quadrature ---")

    // Mathematical Ground Truth for verifying the algorithm:
    // The definite integral of f(x) = x^2 against the weight e^(-x^2) from -inf to +inf 
    // evaluates analytically to exactly: sqrt(pi) / 2
    val exactGroundTruth = sqrt_Pi / 2.0
    println (s"Analytical Ground Truth Target Score: $exactGroundTruth\n")

    // Define the integration problem arrays for testing
    val testingNodes = Array (3, 5)

    for n <- testingNodes do
        println (s"--- Evaluating $n-Node Quadrature Configuration ---")
        
        // Retrieve the precomputed static rules from your generic utility
        val rule = GaussHermiteQuadrature.getRule (n)
        
        // Print the structural coordinate maps generated by the tool
        println ("Generated Quadrature Mapping Layout:")
        for j <- 0 until rule.nodes.length do
            println (s"  Node Index $j | Coordinate Node (xi): ${"%10.6f".format(rule.nodes(j))} | Weight (omega): ${"%10.6f".format(rule.weights(j))}")
        
        // Evaluate the integration test function: f(x) = x^2
        // Gauss-Hermite quadrature says: Integral of f(x)e^(-x^2) dx ≈ sum(omega_j * f(xi_j))
        val numericalApproximation = (0 until rule.nodes.length).map { j =>
            val xi    = rule.nodes(j)
            val omega = rule.weights(j)
            
            val fx = xi * xi                                     // test Function: f(x) = x^2
            omega * fx
        }.sum

        val absoluteError = abs (numericalApproximation - exactGroundTruth)
        
        println (s"Numerical Approximation Result : $numericalApproximation")
        println (s"Computed Absolute Error Residual: ${"%10.2e".format(absoluteError)}")
        
        // Structural validation assert check: 
        // A 3-node or 5-node rule integrates a quadratic polynomial with near-perfect precision
        if (absoluteError < 1e-12) then
            println(s"-> SUCCESS: $n-Node calculation matched ground truth with zero machine leakage.")
        else
            println(s"-> WARNING: Local drift observed.")
        println ("-" * 80)
    end for

    banner ("--- Verified: Context Carrier Compliant for Probit, Poisson, and Beta  ---")

end gaussHermiteQuadratuteTest

