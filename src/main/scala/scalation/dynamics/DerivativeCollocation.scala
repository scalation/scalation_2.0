/** The `DerivativeCollocation` abstract class provides a robust foundation for fitting 
 *  arbitrary compartmental ODE models without using numerical integration solvers.
 *  @param data     a matrix containing the time steps in column 0 and observed metrics in subsequent columns.
 *  @param pBounds  a matrix containing the search space for parameters: row 0 = min, row 1 = max, row 2 = step.
 */
abstract class DerivativeCollocation (data: MatrixD, pBounds: MatrixD):

    // Extract independent time variable and dimensions
    val t: VectorD = data(?, 0)
    val timesteps: Int = t.dim

    // Cache the parameter boundary definitions
    val pMin: VectorD  = pBounds(0)
    val pMax: VectorD  = pBounds(1)
    val pStep: VectorD = pBounds(2)

    //:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Reconstruct all missing/latent compartments algebraically using the raw 
     *  smoothed tracking data and current parameter hypotheses.
     *  @param params  the current parameter vector being evaluated.
     *  @return An array of vectors representing each structural compartment profile.
     */
    def reconstruct (params: VectorD): Array [VectorD]

    //:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Compute the structural discrepancy (SSE) between empirical spline derivatives
     *  and the target model equations.
     *  @param params        the current parameter vector being evaluated.
     *  @param compartments  the system trajectories generated by the reconstruct method.
     *  @return The total Sum of Squared Errors (loss).
     */
    def computeLoss (params: VectorD, compartments: Array [VectorD]): Double

    //:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Helper utility to construct a CubicSpline and safely evaluate its derivative 
     *  smoothly across the entire independent time grid.
     */
    def getDerivatives (profile: VectorD): VectorD =
        val spline = new CubicSpline (t, profile)
        VectorD (for ti <- t yield spline.derivative(ti))
    end getDerivatives

    //:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Core execution engine. Performs a multi-start grid search over the bounded parameter
     *  space to isolate the global minimum without local optimization gradient failures.
     */
    def fit (): (VectorD, Double) =
        var bestLoss   = Double.MaxValue
        var bestParams = new VectorD (pMin.dim)

        //:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
        /** Helper recursive function to evaluate an arbitrary n-dimensional hypergrid loop.
         */
        def searchSpace (index: Int, currentParams: VectorD): Unit =
            if index == pMin.dim then
                val compartments = reconstruct(currentParams)
                val currentLoss  = computeLoss(currentParams, compartments)
                if currentLoss < bestLoss then
                    bestLoss = currentLoss
                    bestParams = currentParams.copy
            else
                var v = pMin(index)
                while v <= pMax(index) do
                    currentParams(index) = v
                    searchSpace(index + 1, currentParams)
                    v += pStep(index)

        searchSpace (0, new VectorD (pMin.dim))
        (bestParams, bestLoss)
    end fit

end DerivativeCollocation


