/** The `seirCollocationTest` main function tests the `SeirCollocation` class.
 *  > runMain scalation.dynamics.seirCollocationTest
 */
@main def seirCollocationTest (): Unit =

    import modeling.forecasting.Example_Covid

    // 1. DATA PREPARATION VIA COV-19 UTILITIES

    // Request your explicit feature matrix array blocks from Example_Covid
    val features   = Array ("new_cases", "new_tests", "positive_rate")
    val dataMatrix = Example_Covid.loadData_yy(features)
    
    val timesteps = dataMatrix.dim
    val totalCols = dataMatrix.dim2

    // Build unified target input matrix (Col 0 = Time, Col 1..N = Loaded Features)
    val inputData = new MatrixD (timesteps, totalCols + 1)

    for i <- 0 until timesteps do
        inputData(i, 0) = i.toDouble                   // inject continuous time index axis into Column 0
        for j <- 0 until totalCols do
            inputData(i, j + 1) = dataMatrix(i, j)     // populate remaining feature tracks

    // 2. DEFINE TUNING GRID SEARCH MATRIX

    // Columns: [0] = Beta, [1] = Alpha, [2] = Gamma
    val bounds = MatrixD ((3, 4), 0.30,  0.10,  0.05,  0.10,   // Row 0: Min Bounds (Sigma min = 10% ascertainment)
                                  1.60,  0.50,  0.35,  0.50,   // Row 1: Max Bounds (Sigma max = 50% ascertainment)
                                  0.05,  0.05,  0.05,  0.05)   // step size

    val populationN = 330000000.0

    val t_vector     = inputData(?, 0)
    val newCases_raw = inputData(?, 1)
    val smoothEngine = new CubicSpline (t_vector, newCases_raw)
    val I_actual     = VectorD (for ti <- t_vector yield smoothEngine.eval (ti))

    // 3. EXECUTE CALIBRATION

    val model = new SeirCollocation (inputData, bounds, populationN)
    val (optimalParams, residualLoss) = model.fit ()

    // Extract smooth fitted array vectors for a localized inspection snapshot
    val finalTrajectories = model.reconstruct (optimalParams)
    val S = finalTrajectories(0)
    val E = finalTrajectories(1)
    val I = finalTrajectories(2)
    val R = finalTrajectories(3)

    val sigma = optimalParams(3)
    val I_predict = new VectorD (timesteps)
    I_predict(0) = I_actual(0) 
    
    for t_idx <- 1 until timesteps do
        val biological_infections = max (0.0, S(t_idx - 1) - S(t_idx))
        I_predict(t_idx)  = biological_infections * sigma

    println (new TestFit (I_actual.dim).testDiagnose (I_actual, I_predict))

    // 4. DISPLAY SUMMARY METRICS

    println (s"=== Modular Parameter Calibration via ScalaTion 2 ===")
    println (s"Optimal Parameters found:")
    println (s" - Beta  (Transmission Rate)        : ${optimalParams(0)}")
    println (s" - Alpha (Incubation Latency Rate)  : ${optimalParams(1)}")
    println (s" - Gamma (Recovery/Removal Velocity): ${optimalParams(2)}")
    println (s" - Sigma (Reporting Rate)           : $sigma")
    println (s"Calculated R0 Baseline Metric       : ${optimalParams(0) / optimalParams(2)}")
    println (s"Global Discrepancy Matrix MSE Loss  : $residualLoss")

    println ("\nSystem State Vectors (First 3 Timesteps):")
    for i <- 0 to 2 do
        println (s"Step $i -> S: ${S(i).toLong}, E: ${E(i).toLong}, I: ${I(i).toLong}, R: ${R(i).toLong}")

end seirCollocationTest

