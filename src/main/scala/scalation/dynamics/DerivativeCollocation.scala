/** The `SeirCollocation` class bridges the general framework with explicit SEIR dynamics.
 *  Assumes raw observed data column 1 maps to the Removed/Deaths (R) group.
 */
class SeirCollocation (data: MatrixD, pBounds: MatrixD, val N: Double) 
      extends DerivativeCollocation (data, pBounds):

    // Pre-calculate smooth R values and R derivatives from column 1
    val R_obs: VectorD = data(?, 1)
    val dR_dt: VectorD = getDerivatives(R_obs)

    //:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Reconstruct/estimate vectors for S, E, I, R.
     *  @param params  the estimated parameters
     */
    override def reconstruct (params: VectorD): Array [VectorD] =
        val alpha = params(1)
        val gamma = params(2)
        val sigma = params(3)         // natively optimize the reporting rate parameter (e.g., 0.1 to 0.8)

        val I_est = new VectorD (timesteps)
        val E_est = new VectorD (timesteps)
        val R_est = new VectorD (timesteps)
        val S_est = new VectorD (timesteps)

       // Localized extraction to guarantee clean thread-safe compile scoping
        val localNewCases = data(?, 1)
        val localSpline   = new CubicSpline (t, localNewCases)
        val cases_smooth  = VectorD (for ti <- t yield localSpline.eval(ti))

        var accumulated_R = 0.0
        // Scaled initialization: map tracking input based on your reporting hypothesis
        I_est(0) = max (10.0, (data(0, 1) / sigma) * 4.0)
        R_est(0) = accumulated_R

        for i <- 1 until timesteps do
            val dt = t(i) - t(i-1)
            // THE STRUCTURAL SHIFT: Scale raw observations up to estimate TRUE latent infections
            val true_new_cases = cases_smooth(i-1) / sigma
            
            I_est(i) = max (0.0, I_est(i-1) + dt * (true_new_cases - (gamma * I_est(i-1))))
            accumulated_R += 0.5 * dt * (gamma * I_est(i-1) + gamma * I_est(i))
            R_est(i) = accumulated_R

        val dI_dt = getDerivatives (I_est)

        for i <- t.indices do
            E_est(i) = max (0.0, (dI_dt(i) + (gamma * I_est(i))) / alpha)
            S_est(i) = max (0.0, N - E_est(i) - I_est(i) - R_est(i))

        Array (S_est, E_est, I_est, R_obs)
    end reconstruct

    //:::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
    /** Compute the loss function (sse).
     */
    override def computeLoss (params: VectorD, compartments: Array [VectorD]): Double =
        val beta  = params(0)
        val alpha = params(1)

        val S_vec = compartments(0)
        val E_vec = compartments(1)
        val I_vec = compartments(2)

        val dE_dt = getDerivatives (E_vec)
        var sse = 0.0

        for i <- t.indices do
            val pred_dE_dt = (beta * S_vec(i) * I_vec(i) / N) - (alpha * E_vec(i))
            val error      = dE_dt(i) - pred_dE_dt
            sse += error * error
        sse / timesteps
    end computeLoss

end SeirCollocation


